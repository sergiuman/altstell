function highlightPath(nodeId) {
    // Clear all highlights
    document.querySelectorAll('.loop-node').forEach(node => node.classList.remove('highlighted'));
    document.querySelectorAll('.loop-arrow').forEach(arrow => arrow.classList.remove('highlighted'));
    
    // Highlight hovered node
    const activeNode = document.getElementById(`node-${nodeId}`);
    if (activeNode) activeNode.classList.add('highlighted');
    
    // Dynamic explanation logic
    const titleEl = document.getElementById('loop-title-dynamic');
    const descEl = document.getElementById('loop-desc-dynamic');
    const explanationBox = document.getElementById('loop-explanation-panel');
    
    if (nodeId === 'delay') {
        explanationBox.classList.add('delay-active');
    } else {
        explanationBox.classList.remove('delay-active');
    }
    
    titleEl.textContent = loopExplorerData[nodeId].title[currentLanguage];
    descEl.textContent = loopExplorerData[nodeId].desc[currentLanguage];
    
    // Arrow Highlight based on loop direction
    if (nodeId === 'fear') {
        document.querySelector('.right-arrow').classList.add('highlighted');
    } else if (nodeId === 'hoarding') {
        document.querySelector('.down-arrow').classList.add('highlighted');
    } else if (nodeId === 'brook') {
        document.querySelector('.left-arrow').classList.add('highlighted');
    } else if (nodeId === 'delay') {
        document.querySelector('.up-arrow').classList.add('highlighted');
    }
}

