function drawChart() {
    const canvas = document.getElementById('bullwhipChart');
    if (!canvas) return;
    const ctx = canvas.getContext('2d');
    
    // Clear canvas
    ctx.clearRect(0, 0, canvas.width, canvas.height);
    
    // Draw Background grids
    ctx.fillStyle = '#0f1f15';
    ctx.fillRect(0, 0, canvas.width, canvas.height);
    
    // Grid settings
    const padding = 45;
    const chartWidth = canvas.width - (padding * 2);
    const chartHeight = canvas.height - (padding * 2);
    
    // Find min and max for scaling
    // Math checks
    let allValues = [...orderHistory, ...demandHistory, ...inventoryHistory];
    let maxVal = Math.max(...allValues, 10);
    let minVal = Math.min(...allValues, -10);
    
    // Draw zero line
    const zeroY = padding + (maxVal / (maxVal - minVal)) * chartHeight;
    ctx.strokeStyle = 'rgba(255, 255, 255, 0.2)';
    ctx.lineWidth = 1;
    ctx.beginPath();
    ctx.moveTo(padding, zeroY);
    ctx.lineTo(canvas.width - padding, zeroY);
    ctx.stroke();
    
    // Y-Axis labels (ticks)
    ctx.fillStyle = '#a0b0a5';
    ctx.font = '10px Outfit';
    ctx.textAlign = 'right';
    
    const steps = 5;
    for (let i = 0; i <= steps; i++) {
        const val = minVal + ((maxVal - minVal) / steps) * i;
        const y = padding + chartHeight - (i / steps) * chartHeight;
        ctx.fillText(Math.round(val), padding - 8, y + 3);
        
        // Horizontal grid lines
        ctx.strokeStyle = 'rgba(255, 255, 255, 0.05)';
        ctx.beginPath();
        ctx.moveTo(padding, y);
        ctx.lineTo(canvas.width - padding, y);
        ctx.stroke();
    }
    
    // X-Axis Weeks labels
    ctx.textAlign = 'center';
    const weeksCount = 15;
    for (let w = 1; w <= weeksCount; w++) {
        const x = padding + ((w - 1) / (weeksCount - 1)) * chartWidth;
        ctx.fillText(w, x, canvas.height - padding + 15);
    }
    
    // Helper function to convert (week index, value) to pixel (x, y)
    function getCoords(weekIdx, val) {
        const x = padding + (weekIdx / (weeksCount - 1)) * chartWidth;
        const y = padding + chartHeight - ((val - minVal) / (maxVal - minVal)) * chartHeight;
        return { x, y };
    }
    
    // LINE 1: Customer Demand (Blue)
    ctx.strokeStyle = '#00b0ff';
    ctx.lineWidth = 3;
    ctx.beginPath();
    for (let i = 0; i < demandHistory.length; i++) {
        const pt = getCoords(i, demandHistory[i]);
        if (i === 0) ctx.moveTo(pt.x, pt.y);
        else ctx.lineTo(pt.x, pt.y);
    }
    ctx.stroke();
    
    // LINE 2: Player Orders (Gold)
    ctx.strokeStyle = '#ffd700';
    ctx.lineWidth = 3;
    ctx.beginPath();
    for (let i = 0; i < orderHistory.length - 1; i++) {
        const pt = getCoords(i, orderHistory[i]);
        if (i === 0) ctx.moveTo(pt.x, pt.y);
        else ctx.lineTo(pt.x, pt.y);
    }
    ctx.stroke();
    
    // LINE 3: Inventory Levels (Green)
    ctx.strokeStyle = '#14db72';
    ctx.lineWidth = 3;
    ctx.beginPath();
    for (let i = 0; i < inventoryHistory.length - 1; i++) {
        const pt = getCoords(i, inventoryHistory[i]);
        if (i === 0) ctx.moveTo(pt.x, pt.y);
        else ctx.lineTo(pt.x, pt.y);
    }
    ctx.stroke();
    
    // Draw Legend
    ctx.font = '11px Outfit';
    ctx.textAlign = 'left';
    
    // Demand Legend
    ctx.fillStyle = '#00b0ff';
    ctx.fillRect(padding, 15, 12, 12);
    ctx.fillStyle = '#fff';
    ctx.fillText(currentLanguage === 'en' ? 'Customer Demand' : 'Cererea Clienților', padding + 18, 25);
    
    // Orders Legend
    ctx.fillStyle = '#ffd700';
    ctx.fillRect(padding + 160, 15, 12, 12);
    ctx.fillStyle = '#fff';
    ctx.fillText(currentLanguage === 'en' ? 'Your Orders' : 'Comenzile Tale', padding + 178, 25);
    
    // Stock Legend
    ctx.fillStyle = '#14db72';
    ctx.fillRect(padding + 290, 15, 12, 12);
    ctx.fillStyle = '#fff';
    ctx.fillText(currentLanguage === 'en' ? 'Inventory / Backlog' : 'Stoc / Deficit', padding + 308, 25);
}

